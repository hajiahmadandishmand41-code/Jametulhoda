function normalizePhone(string $countryCode, string $phone): string {
    $dial = preg_replace('/\D+/', '', $countryCode) ?? '';
    $num = preg_replace('/\D+/', '', $phone) ?? '';
    $num = ltrim($num, '0');
    if ($dial !== '' && str_starts_with($num, $dial)) {
        $num = substr($num, strlen($dial));
        $num = ltrim($num, '0');
    }
    if ($num === '') return '';
    return $dial !== '' ? '+' . $dial . $num : '+' . $num;
}

function isMemberLoggedIn(): bool {
    startSecureSession();
    if (empty($_SESSION['member_id'])) return false;
    if (($_SESSION['last_member_activity'] ?? 0) < time() - SESSION_LIFETIME) {
        unset($_SESSION['member_id'], $_SESSION['member_name'], $_SESSION['member_auth_version'], $_SESSION['last_member_activity']);
        return false;
    }
    try {
        ensureMembersSchema();
        $stmt = getDB()->prepare('SELECT is_active, auth_version, full_name FROM members WHERE id=?');
        $stmt->execute([(int)$_SESSION['member_id']]);
        $row = $stmt->fetch();
    } catch (Throwable $e) {
        return false;
    }
    if (!$row || (int)$row['is_active'] !== 1 || (int)$row['auth_version'] !== (int)($_SESSION['member_auth_version'] ?? 0)) {
        unset($_SESSION['member_id'], $_SESSION['member_name'], $_SESSION['member_auth_version'], $_SESSION['last_member_activity']);
        return false;
    }
    $_SESSION['member_name'] = $row['full_name'];
    $_SESSION['last_member_activity'] = time();
    return true;
}

function requireMember(): void {
    if (!isMemberLoggedIn()) {
        header('Location: ' . loginUrl());
        exit;
    }
}

