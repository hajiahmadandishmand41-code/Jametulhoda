function ensureMembersSchema(): void {
    static $done = false;
    if ($done) return;
    $done = true;
    try {
        $db = getDB();
        $driver = databaseDriver();
        if ($driver === 'mysql') {
            $db->exec("CREATE TABLE IF NOT EXISTS members (
                id INT AUTO_INCREMENT PRIMARY KEY,
                full_name VARCHAR(120) NOT NULL,
                country VARCHAR(80) NOT NULL DEFAULT '',
                country_code VARCHAR(8) NOT NULL DEFAULT '',
                phone VARCHAR(32) NOT NULL,
                phone_normalized VARCHAR(32) NOT NULL,
                email VARCHAR(180) NULL,
                password VARCHAR(255) NOT NULL,
                is_active SMALLINT NOT NULL DEFAULT 1,
                agreed_terms SMALLINT NOT NULL DEFAULT 0,
                auth_version INT NOT NULL DEFAULT 1,
                last_login DATETIME NULL,
                created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
                UNIQUE KEY members_phone_unique (phone_normalized),
                UNIQUE KEY members_email_unique (email)
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");
        } elseif ($driver === 'sqlite') {
            $db->exec("CREATE TABLE IF NOT EXISTS members (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                full_name TEXT NOT NULL,
                country TEXT NOT NULL DEFAULT '',
                country_code TEXT NOT NULL DEFAULT '',
                phone TEXT NOT NULL,
                phone_normalized TEXT NOT NULL UNIQUE,
                email TEXT UNIQUE,
                password TEXT NOT NULL,
                is_active INTEGER NOT NULL DEFAULT 1,
                agreed_terms INTEGER NOT NULL DEFAULT 0,
                auth_version INTEGER NOT NULL DEFAULT 1,
                last_login TEXT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            )");
        } else {
            $db->exec("CREATE TABLE IF NOT EXISTS members (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                full_name VARCHAR(120) NOT NULL,
                country VARCHAR(80) NOT NULL DEFAULT '',
                country_code VARCHAR(8) NOT NULL DEFAULT '',
                phone VARCHAR(32) NOT NULL,
                phone_normalized VARCHAR(32) NOT NULL UNIQUE,
                email VARCHAR(180) NULL UNIQUE,
                password VARCHAR(255) NOT NULL,
                is_active SMALLINT NOT NULL DEFAULT 1,
                agreed_terms SMALLINT NOT NULL DEFAULT 0,
                auth_version INT NOT NULL DEFAULT 1,
                last_login TIMESTAMPTZ NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )");
        }
    } catch (Throwable $e) {
        error_log('Members schema ensure failed: ' . get_class($e));
    }
}

