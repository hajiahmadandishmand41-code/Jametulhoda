function registerMember(array $data): array {
    ensureMembersSchema();
    $name = trim((string)($data['full_name'] ?? ''));
    $country = (string)($data['country'] ?? '');
    $phone = trim((string)($data['phone'] ?? ''));
    $email = mb_strtolower(trim((string)($data['email'] ?? '')));
    $password = (string)($data['password'] ?? '');
    $confirm = (string)($data['password_confirm'] ?? '');
    $agreed = !empty($data['agreed_terms']);

    $countries = jhd_countries();
    if (!isset($countries[$country])) return ['ok' => false, 'error' => 'کشور انتخاب‌شده معتبر نیست.'];
    $dial = (string)$countries[$country]['dial'];
    $countryName = (string)$countries[$country]['name'];

    if (mb_strlen($name) < 2 || mb_strlen($name) > 120) return ['ok' => false, 'error' => 'نام را به‌درستی وارد کنید.'];
    if (!$agreed) return ['ok' => false, 'error' => 'برای ثبت‌نام باید با قوانین سایت موافق باشید.'];
    if (strlen($password) < 8 || strlen($password) > 4096) return ['ok' => false, 'error' => 'رمز عبور باید حداقل ۸ نویسه باشد.'];
    if (!hash_equals($password, $confirm)) return ['ok' => false, 'error' => 'تکرار رمز عبور مطابقت ندارد.'];
    if ($email !== '' && !filter_var($email, FILTER_VALIDATE_EMAIL)) return ['ok' => false, 'error' => 'ایمیل واردشده معتبر نیست.'];

    $normalized = normalizePhone($dial, $phone);
    if ($normalized === '' || strlen($normalized) < 8) return ['ok' => false, 'error' => 'شماره تلفن معتبر نیست.'];

    $db = getDB();
    $ipKey = hash('sha256', 'member-reg:' . clientIp());
    if (recordLoginAttempt($db, $ipKey) > 20) return ['ok' => false, 'error' => 'تعداد تلاش‌ها بیش از حد است. بعداً دوباره تلاش کنید.'];

    $dup = $db->prepare('SELECT id FROM members WHERE phone_normalized=? LIMIT 1');
    $dup->execute([$normalized]);
    if ($dup->fetch()) return ['ok' => false, 'error' => 'امکان ایجاد حساب با این اطلاعات وجود ندارد.'];
    if ($email !== '') {
        $dupE = $db->prepare('SELECT id FROM members WHERE email=? LIMIT 1');
        $dupE->execute([$email]);
        if ($dupE->fetch()) return ['ok' => false, 'error' => 'امکان ایجاد حساب با این اطلاعات وجود ندارد.'];
    }

    $hash = password_hash($password, PASSWORD_DEFAULT);
    $sql = 'INSERT INTO members (full_name, country, country_code, phone, phone_normalized, email, password, is_active, agreed_terms, auth_version) VALUES (?,?,?,?,?,?,?,1,1,1)';
    if (databaseDriver() === 'pgsql') {
        $stmt = $db->prepare($sql . ' RETURNING id');
        $stmt->execute([$name, $countryName, $dial, $phone, $normalized, $email !== '' ? $email : null, $hash]);
        $id = (int)$stmt->fetchColumn();
    } else {
        $stmt = $db->prepare($sql);
        $stmt->execute([$name, $countryName, $dial, $phone, $normalized, $email !== '' ? $email : null, $hash]);
        $id = (int)$db->lastInsertId();
    }
    if ($id < 1) return ['ok' => false, 'error' => 'ثبت‌نام انجام نشد. دوباره تلاش کنید.'];

    startSecureSession();
    session_regenerate_id(true);
    $_SESSION['member_id'] = $id;
    $_SESSION['member_name'] = $name;
    $_SESSION['member_auth_version'] = 1;
    $_SESSION['last_member_activity'] = time();
    return ['ok' => true, 'id' => $id];
}

function changeMemberPassword(int $memberId, string $current, string $next): bool {
    if ($memberId < 1 || strlen($next) < 8 || strlen($next) > 4096) return false;
    ensureMembersSchema();
    $stmt = getDB()->prepare('SELECT password FROM members WHERE id=? AND is_active=1');
    $stmt->execute([$memberId]);
    $hash = (string)$stmt->fetchColumn();
    if (!jhd_password_is_hash($hash) || !password_verify($current, $hash)) return false;
    getDB()->prepare('UPDATE members SET password=?, auth_version = COALESCE(auth_version,1)+1 WHERE id=?')
        ->execute([password_hash($next, PASSWORD_DEFAULT), $memberId]);
    startSecureSession();
    $_SESSION['member_auth_version'] = (int)($_SESSION['member_auth_version'] ?? 1) + 1;
    return true;
}

function logoutMember(): void {
    startSecureSession();
    unset($_SESSION['member_id'], $_SESSION['member_name'], $_SESSION['member_auth_version'], $_SESSION['last_member_activity']);
    header('Location: ' . url());
    exit;
}
