function loginMember(string $identifier, string $password): bool {
    if (strlen($identifier) > 180 || strlen($password) > 4096) return false;
    ensureMembersSchema();
    $db = getDB();
    $ipKey = hash('sha256', 'member-ip:' . clientIp());
    $idKey = hash('sha256', 'member:' . mb_strtolower(trim($identifier)));
    if (recordLoginAttempt($db, $ipKey) > 50) return false;
    if (recordLoginAttempt($db, $idKey) > 8) return false;

    $ident = trim($identifier);
