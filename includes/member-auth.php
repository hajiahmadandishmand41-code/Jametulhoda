        $stmt = $db->prepare('SELECT * FROM members WHERE email=? LIMIT 1');
        $stmt->execute([mb_strtolower($ident)]);
        $member = $stmt->fetch() ?: null;
    } else {
        $normalized = normalizePhone('', $ident);
        $stmt = $db->prepare('SELECT * FROM members WHERE phone_normalized=? OR phone=? LIMIT 1');
        $stmt->execute([$normalized !== '' ? $normalized : $ident, $ident]);
        $member = $stmt->fetch() ?: null;
        if (!$member) {
            $stmt = $db->prepare('SELECT * FROM members WHERE phone_normalized LIKE ? LIMIT 1');
            $tail = '%' . preg_replace('/\D+/', '', $ident);
            $stmt->execute([$tail]);
            $member = $stmt->fetch() ?: null;
        }
    }
    if (!$member) {
        password_verify($password, '$2y$10$usesomesillystringfore7wTCnyKPeogVA6awaz8iYupZHBMjqZ');
        return false;
    }
    if ((int)$member['is_active'] !== 1) return false;
    $stored = (string)($member['password'] ?? '');
    if (!jhd_password_is_hash($stored) || !password_verify($password, $stored)) return false;

    startSecureSession();
